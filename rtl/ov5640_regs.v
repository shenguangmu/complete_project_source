// =====================================================================
//  ov5640_regs.v —— OV5640 寄存器配置 ROM
//
//  =====================================================================
//  ⚠⚠⚠  这个文件目前是【占位】,不是可用的配置表  ⚠⚠⚠
//  =====================================================================
//
//  ─────────────────────────────────────────────────────────────────
//  为什么没有填真表
//  ─────────────────────────────────────────────────────────────────
//  OV5640 要正常出 640x480 RGB565 图像，需要约 **上百个寄存器** 的
//  精确配置：PLL 倍频/分频、时钟树、曝光、增益、白平衡、输出格式
//  (0x4300)、ISP 参数、时序窗口 (0x3800-0x3829) 等等。
//
//  这些值**必须来自可靠来源** —— 原厂应用笔记 (OV5640_应用指南)
//  或成熟开源工程。**不能凭理解凑**，原因是：
//
//    * 寄存器之间存在依赖顺序（先改时钟再改格式），顺序错会锁死
//    * 值错的表现是"完全没有图像"，而有十几种原因都表现为没图像 ——
//      此时你无法区分是寄存器表错、还是接线错、还是时序错
//    * OV5640 的寄存器手册不公开完整细节，网上流传的表多为抄改
//
//  本项目的定位是 **PL 侧图像处理**，不是摄像头驱动开发。
//  在这张表上花时间属于"自己造轮子"，而且造错的风险很高。
//
//  ─────────────────────────────────────────────────────────────────
//  怎么填（按推荐顺序）
//  ─────────────────────────────────────────────────────────────────
//
//  【方案 1 · 最省事】用你买的那块 PMOD-CAMERA 配套的资料
//      MUSE LAB 的模块通常提供例程。如果有 OV5640 的初始化序列，
//      直接抄进下面的 ROM。
//
//  【方案 2】用 Pynq-CV-OV5640 开源项目里的配置
//      该项目在 PYNQ-Z2 上跑通过，说明它的表**配 640x480 是有效的**。
//      项目里有 `ov5640_config.py`，把它转成 Verilog ROM 即可。
//      仓库：github.com/xupsh/Pynq-CV-OV5640
//
//  【方案 3】正点原子的 OV5640 例程（FPGA 版）
//      正点原子的 FPGA 例程里有完整的 Verilog 配置表，
//      而且是按 RGB565 + DVP 写的，与我们的场景最接近。
//      即使模组不是正点原子的，OV5640 芯片本身寄存器一致，表通用。
//
//  【方案 4 · 不推荐】自己从 OV5640 数据手册推
//      需要同时对照 3 份文档（datasheet / application note /
//      register map），且中间状态无法验证。**不建议。**
//
//  ─────────────────────────────────────────────────────────────────
//  ROM 接口（与 sccb_master 对接）
//  ─────────────────────────────────────────────────────────────────
//      tbl_addr : 表项索引，0 起递增
//      tbl_data : {寄存器地址[15:0], 数据[7:0]}，共 24 位
//      N_REGS   : 表项总数（sccb_master 配到这就停）
//
//  ⚠ 注意 sccb_master 的参数 N_REGS 必须与本文件的实际条目数一致，
//    改了表就要同步改 BD 里 sccb_0 的 N_REGS，否则配到一半就停
//    （或越过表尾读到垃圾值）。
// =====================================================================

`timescale 1ns / 1ps

module ov5640_regs #(
    // ⚠ 改这里的同时要改 BD 里 sccb_0 的 N_REGS 参数
    parameter N_REGS   = 8,
    // 地址位宽。必须与 sccb_master 的 tbl_addr 位宽**一致** ——
    // 早期用 12 位而 sccb 用 8 位，BD 会报
    //   [BD 41-2383] Width mismatch ... Only lower order bits will be
    //   connected, and other input bits will be left unconnected
    // 高 4 位悬空意味着**表一旦超过 256 项就会静默读错**。
    // 8 位足够 256 项，而 OV5640 的配置表通常 100~200 项。
    parameter ADDR_W   = 8
) (
    input  wire [ADDR_W-1:0]  tbl_addr,   // 表项索引
    output wire [23:0]        tbl_data    // {reg_addr[15:0], value[7:0]}
);

    // ------------------------------------------------------------------
    //  ⚠⚠ 占位表 —— 【必须替换成真实配置】
    //
    //  下面这几条只是为了：
    //    1. 让设计能综合通过（ROM 有确定内容，不是 x）
    //    2. 让 sccb_master 的时序有东西可发（能用 ILA 看到 SCL 波形）
    //
    //  **它们不足以让 OV5640 出图。** 上板后你会看到：
    //    - io_scl 有 100kHz 方波 ✓（说明 SCCB 在跑）
    //    - io_pclk 一直没波形 ✗（说明摄像头没被正确配置）
    //  这是**预期行为**，不是接线问题。
    //
    //  替换方法见文件头说明。替换后记得改 N_REGS 和 BD 里的参数。
    // ------------------------------------------------------------------
    reg [23:0] rom [0:N_REGS-1];

    initial begin
        // OV5640 软复位 / 基础时钟相关（这几条是几乎所有表都有的开头）
        rom[0] = 24'h31_03_11;   // 系统复位相关
        rom[1] = 24'h30_08_82;   // 时钟使能
        rom[2] = 24'h30_35_11;   // PLL 控制
        rom[3] = 24'h30_36_3C;   // PLL 倍频
        rom[4] = 24'h30_37_13;   // PLL 分频
        rom[5] = 24'h38_24_00;   // PCLK 分频（⚠ 降 PCLK 改这里，见下）
        rom[6] = 24'h43_00_61;   // 输出格式（0x61 = RGB565？待核实）
        rom[7] = 24'h50_3D_80;   // 测试图案

        // ⚠ 注意：以上 8 条**未经任何验证**，尤其 rom[5] 和 rom[6]
        //    的值是我按常见配置写的猜测。**不要照抄上板。**
    end

    assign tbl_data = rom[tbl_addr];

    // ------------------------------------------------------------------
    //  调试备注：关于降低 PCLK
    // ------------------------------------------------------------------
    //  若实测 PCLK 太快导致采样错误（见 docs/硬件采购清单.md §1.3），
    //  改 OV5640 的 PCLK 分频寄存器即可 —— 在真实配置表里它就是
    //  某一条 {0x3824, 值}。本占位表把它放在 rom[5] 只是为了标注位置。
    //
    //  这也是"必须有真表"的另一个理由：**你连调 PCLK 都要先有表**。
    // ------------------------------------------------------------------

endmodule
