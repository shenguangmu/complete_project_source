// =====================================================================
//  iobuf_wrap.v —— IOBUF 三态缓冲的包装模块
//
//  ─────────────────────────────────────────────────────────────────
//  为什么需要这个文件
//  ─────────────────────────────────────────────────────────────────
//  SCCB 的 SDA 是**开漏双向**线：FPGA 拉低时驱动，不驱动时释放
//  让外部上拉把它拉高。
//
//  实现这个行为要用 Xilinx 的 IOBUF 原语。但 **Vivado 的 Block
//  Design 里无法直接例化原语** —— `create_bd_cell` 只能引用 IP 或
//  模块（module reference），原语不在那两类里。
//
//  所以包一层：本模块内部例化 IOBUF，对外暴露普通的
//  oe / o / i 三根线，BD 里就能当作普通 module 用。
//
//  ─────────────────────────────────────────────────────────────────
//  IOBUF 的真值表（Xilinx 原语）
//  ─────────────────────────────────────────────────────────────────
//      T   I   IO      O
//      0   x   Z       读回 IO 上的实际电平
//      1   0   0       0
//      1   1   1       1
//
//  即：T=1 时驱动，T=0 时高阻。
//
//  ⚠ 注意本模块用 oe（output enable，高有效驱动）作为对外的语义，
//    与 IOBUF 的 T 引脚同极性，不需要取反。
// =====================================================================

`timescale 1ns / 1ps

module iobuf_wrap (
    // ---- 内部侧（接 PL 逻辑）----
    input  wire io_drv,     // 1 = 驱动总线（IOBUF 的 T）
    input  wire io_out,     // 要驱动的值（IOBUF 的 I）
    output wire io_in,      // 从总线读回的值（IOBUF 的 O）

    // ---- 外部侧（接物理引脚）----
    inout  wire io_pad
);

    // 直接例化 Xilinx 原语。
    // ⚠ IOBUF 是 7 系列的通用三态缓冲，Zynq-7020 上有。
    IOBUF u_iobuf (
        .O  (io_in),    // 从 pad 读回
        .IO (io_pad),   // 双向
        .I  (io_out),   // 要驱动的值
        .T  (~io_drv)   // ⚠ IOBUF 的 T 是"三态使能"（高=高阻），
                        //   与"驱动使能"相反，所以这里取反
    );

endmodule
